"use client";
import Link from "next/link";
import * as DropdownMenu from "@radix-ui/react-dropdown-menu";
import { ChevronDown, Compass, RotateCcw, Wifi, WifiOff } from "lucide-react";
import { useRepo, useSession } from "@/data/client";
import { LANGUAGES } from "@/i18n";
import { useT } from "@/i18n/useT";
import { Badge, Button, Tooltip } from "@/components/ui";
import type { Language } from "@/domain";
import { PUBLIC_ROUTES } from "./routes";
import { isLiveAiConfigured } from "./aiMode";

export function Logo() {
  return (
    <Link href="/" className="flex items-center gap-2 rounded-lg font-bold text-brand-900" aria-label="ClassRelay home">
      <span aria-hidden className="grid size-8 place-items-center rounded-xl bg-gradient-to-br from-brand-700 to-teal-600 text-sm text-white">CR</span>
      <span className="text-lg tracking-tight">ClassRelay</span>
    </Link>
  );
}

export function HonestyBadges() {
  const t = useT();
  const { mode } = useRepo();
  const live = isLiveAiConfigured();
  return (
    <div className="flex flex-wrap items-center gap-1.5" aria-label="Honesty labels">
      <Tooltip content="All records are synthetic, generated by a seeded deterministic generator.">
        <Badge tone="amber" tabIndex={0}>{t("badge.demoData")}</Badge>
      </Tooltip>
      <Tooltip content={mode === "sandbox" ? "No Supabase keys: data lives in this browser only. Migrations and RLS still ship (see /data)." : "Persisted to Supabase Postgres with RLS."}>
        <Badge tone="brand" tabIndex={0}>{mode === "sandbox" ? t("badge.dataSandbox") : t("badge.dataSupabase")}</Badge>
      </Tooltip>
      <Tooltip content={live ? "Agents call the Claude API through server routes." : "No AI key: agents return recorded sample outputs."}>
        <Badge tone="teal" tabIndex={0}>{live ? t("badge.liveAi") : t("badge.sampleMode")}</Badge>
      </Tooltip>
    </div>
  );
}

export function ExploreMenu() {
  const t = useT();
  return (
    <DropdownMenu.Root>
      <DropdownMenu.Trigger asChild>
        <Button variant="outline" size="sm" aria-label={t("shell.explore")}>
          <Compass aria-hidden /> {t("shell.explore")} <ChevronDown aria-hidden />
        </Button>
      </DropdownMenu.Trigger>
      <DropdownMenu.Portal>
        <DropdownMenu.Content align="end" sideOffset={6} className="z-50 max-h-[70vh] w-72 overflow-y-auto rounded-2xl border border-slate-200 bg-white p-1.5 shadow-xl">
          {PUBLIC_ROUTES.map((r) => (
            <DropdownMenu.Item key={r.href} asChild>
              <Link href={r.href} className="flex flex-col rounded-xl px-3 py-2 text-sm outline-none data-[highlighted]:bg-brand-50">
                <span className="font-semibold text-slate-900">
                  {t(r.key)} <span className="font-mono text-xs font-normal text-slate-600">{r.href}</span>
                </span>
                <span className="text-xs text-slate-600">{r.desc}</span>
              </Link>
            </DropdownMenu.Item>
          ))}
        </DropdownMenu.Content>
      </DropdownMenu.Portal>
    </DropdownMenu.Root>
  );
}

export function LanguageSwitcher() {
  const t = useT();
  const { session, setSession } = useSession();
  return (
    <label className="flex items-center gap-1 text-sm">
      <span className="sr-only">{t("shell.language")}</span>
      <select
        aria-label={t("shell.language")}
        value={session.language}
        onChange={(e) => setSession({ language: e.target.value as Language })}
        className="h-8 rounded-lg border border-slate-300 bg-white px-2 text-sm text-slate-900"
      >
        {LANGUAGES.map((l) => (
          <option key={l.code} value={l.code}>
            {l.native}
          </option>
        ))}
      </select>
    </label>
  );
}

export function SiteHeader() {
  const t = useT();
  const { reset } = useRepo();
  const { session, setSession } = useSession();
  return (
    <header className="sticky top-0 z-40 border-b border-slate-200 bg-white/95 backdrop-blur">
      <a href="#main" className="skip-link">
        {t("shell.skip")}
      </a>
      <div className="mx-auto flex max-w-7xl flex-wrap items-center gap-3 px-4 py-2.5">
        <Logo />
        <div className="hidden md:block">
          <HonestyBadges />
        </div>
        <div className="ml-auto flex items-center gap-2">
          <LanguageSwitcher />
          <Tooltip content={t("shell.lowBandwidth")}>
            <Button
              variant="ghost"
              size="icon"
              aria-pressed={session.lowBandwidth}
              aria-label={t("shell.lowBandwidth")}
              onClick={() => {
                setSession({ lowBandwidth: !session.lowBandwidth });
                document.documentElement.classList.toggle("low-bandwidth", !session.lowBandwidth);
              }}
            >
              {session.lowBandwidth ? <WifiOff aria-hidden /> : <Wifi aria-hidden />}
            </Button>
          </Tooltip>
          <Button
            variant="ghost"
            size="sm"
            onClick={() => {
              if (window.confirm(t("shell.resetConfirm"))) reset();
            }}
          >
            <RotateCcw aria-hidden /> <span className="hidden sm:inline">{t("shell.reset")}</span>
          </Button>
          <ExploreMenu />
        </div>
      </div>
      <div className="border-t border-slate-100 px-4 py-1.5 md:hidden">
        <HonestyBadges />
      </div>
    </header>
  );
}

export function SiteFooter() {
  const t = useT();
  return (
    <footer className="mt-12 border-t border-slate-200 bg-white pb-24 md:pb-0">
      <div className="mx-auto max-w-7xl px-4 py-8">
        <div className="flex flex-col gap-6 md:flex-row md:justify-between">
          <div className="max-w-sm">
            <Logo />
            <p className="mt-2 text-sm text-slate-700">{t("brand.tagline")}</p>
            <p className="mt-2 text-xs text-slate-600">{t("footer.honesty")}</p>
          </div>
          <nav aria-label="Public routes" className="grid grid-cols-2 gap-x-8 gap-y-1.5 sm:grid-cols-3">
            {PUBLIC_ROUTES.map((r) => (
              <Link key={r.href} href={r.href} className="text-sm text-brand-800 underline-offset-4 hover:underline">
                {t(r.key)}
              </Link>
            ))}
          </nav>
        </div>
      </div>
    </footer>
  );
}
